const {app,BrowserWindow,Menu,dialog}=require('electron');
const fs=require('fs'),path=require('path'),assert=require('assert/strict');
const root=fs.mkdtempSync(path.join(__dirname,'..','qa-artifacts','host-'));
const workspace=path.join(root,'project'),outside=path.join(root,'outside'),profile=path.join(root,'profile');
for(const dir of [workspace,outside,profile])fs.mkdirSync(dir,{recursive:true});
fs.writeFileSync(path.join(workspace,'source.ts'),'export const ok = true;');
fs.writeFileSync(path.join(workspace,'binary.exe'),Buffer.from([77,90,0,1]));
fs.writeFileSync(path.join(workspace,'large.txt'),Buffer.alloc(2000001,65));
fs.writeFileSync(path.join(outside,'private.txt'),'QA outside project');
fs.symlinkSync(outside,path.join(workspace,'junction'),'junction');
fs.writeFileSync(path.join(profile,'settings.json'),JSON.stringify({cwd:workspace,projects:[workspace],agentEngine:'web:doubao',activeWebProfile:'doubao',lastMode:'web',confirmWebSend:true}));
process.env.MY_HARNESS_DATA_DIR=profile;
process.env.MY_HARNESS_ENGINE_HOME=path.join(root,'engine');
process.env.MY_HARNESS_SCREENSHOT=path.join(root,'startup.png');
for(const stream of [process.stdout,process.stderr])stream.on('error',error=>{if(error.code!=='EPIPE')throw error;});
require('../dist/main');
app.whenReady().then(async()=>{
  try{
    let win;
    for(let i=0;i<30;i++){
      win=BrowserWindow.getAllWindows()[0];
      if(win&&!win.webContents.isLoading()&&await win.webContents.executeJavaScript('Boolean(window.myHarness&&document.getElementById("composer"))'))break;
      await new Promise(resolve=>setTimeout(resolve,50));
    }
    const run=code=>win.webContents.executeJavaScript(code);
    const invoke=(method,...args)=>run('window.myHarness.'+method+'(...'+JSON.stringify(args)+')');
    const value=await invoke('getState');
    assert.equal(value.agentState.error,undefined,JSON.stringify(value.agentState));
    for(const key of ['agentEngine','activeWebProfile','lastMode','confirmWebSend'])assert.equal(key in value.settings,false);
    assert.equal(await run('Object.keys(myHarness).some(k=>/web|login/i.test(k))'),false);
    assert.equal((await invoke('readFile',path.join(workspace,'source.ts'))).kind,'text');
    assert.equal((await invoke('readFile',path.join(workspace,'binary.exe'))).kind,'binary');
    assert.equal((await invoke('readFile',path.join(workspace,'large.txt'))).kind,'large');
    await assert.rejects(()=>invoke('readFile',path.join(outside,'private.txt')),/超出当前工作区/);
    await assert.rejects(()=>invoke('readFile',path.join(workspace,'junction','private.txt')),/超出当前工作区/);
    await assert.rejects(()=>invoke('listDirectory',outside),/超出当前工作区/);
    const folderRef = await invoke('referenceFolder',workspace);
    assert.equal(folderRef.relativePath,'.');
    await assert.rejects(()=>invoke('referenceFolder',outside),/当前项目/);
    await assert.rejects(()=>invoke('referenceFolder',path.join(workspace,'junction')),/当前项目/);
    await assert.rejects(()=>invoke('referenceFolder',path.join(workspace,'source.ts')),/不是文件夹/);
    const {MydexAppServer}=require('../dist/mydexAppServer');
    const originalStart=MydexAppServer.prototype.startTurn;
    let engine,keepRunning=false,readiness='ready',promptCount=0,dialogAnswer=0;
    const originalReadiness=MydexAppServer.prototype.sandboxReadiness;
    console.log('READ-ONLY sandbox readiness:',await invoke('sandboxStatus'));
    MydexAppServer.prototype.sandboxReadiness=async()=>({status:readiness});
    const originalDialog=dialog.showMessageBox;
    dialog.showMessageBox=async()=>{promptCount++;return{response:dialogAnswer};};
    MydexAppServer.prototype.startTurn=async function(threadId,prompt,settings){engine=this;if(!keepRunning)this.emit('notification',{method:'turn/completed',params:{threadId,turn:{id:'qa-folder',status:'completed'}}});return{id:'qa-folder',receivedPrompt:prompt,settings};};
    const submitted=await invoke('startTurn','qa-thread','分析引用目录',[folderRef]);
    assert.ok(submitted.receivedPrompt.includes('My Harness 文件夹引用'));
    assert.ok(!submitted.receivedPrompt.includes('export const ok'));
    await assert.rejects(()=>invoke('startTurn','qa-thread','bad',[{...folderRef,workspace:outside}]),/项目已切换/);
    await assert.rejects(()=>invoke('startTurn','qa-thread','bad',[{...folderRef,path:outside}]),/当前项目/);
    assert.equal((await invoke('getPermissions','qa-thread')).sandbox,'workspace-write');
    assert.equal((await invoke('setPermissions','qa-thread','readOnly')).sandbox,'read-only');
    assert.equal((await invoke('setPermissions','qa-thread','full')).sandbox,'read-only');assert.equal(promptCount,1);
    dialogAnswer=1;await invoke('setPermissions','B','full');
    assert.equal((await invoke('getPermissions','qa-thread')).sandbox,'read-only');
    readiness='notConfigured';await assert.rejects(()=>invoke('startTurn','qa-thread','test',[]),/沙箱尚未就绪/);
    assert.equal((await invoke('startTurn','B','test',[])).settings.sandbox,'danger-full-access');
    readiness='ready';keepRunning=true;
    const a=await invoke('startTurn','qa-thread','test',[]);assert.equal(a.settings.sandbox,'read-only');
    await assert.rejects(()=>invoke('startTurn','qa-thread','duplicate',[]),/正在运行/);
    await assert.rejects(()=>invoke('setPermissions','qa-thread','full'),/停止此对话/);
    await assert.rejects(()=>invoke('restartAgent'),/仍有对话/);
    await assert.rejects(()=>invoke('updateSettings',{apiBaseUrl:'http://127.0.0.1:1/v1'}),/仍有对话/);
    const originalRespond=engine.respond;const responses=[];engine.respond=(id,result)=>responses.push({id,result});
    engine.emit('request',{id:99,method:'item/commandExecution/requestApproval',params:{threadId:'qa-thread',availableDecisions:['accept','decline']}});
    await assert.rejects(()=>invoke('approve',99,'acceptForSession'),/不允许/);
    await invoke('approve',99,'accept');await assert.rejects(()=>invoke('approve',99,'accept'),/失效/);
    engine.emit('request',{id:100,method:'item/permissions/requestApproval',params:{threadId:'B',permissions:{network:{enabled:true},fileSystem:null}}});
    await invoke('grantPermissions',100,true,'turn');assert.deepEqual(responses.at(-1),{id:100,result:{permissions:{network:{enabled:true}},scope:'turn'}});
    engine.emit('request',{id:101,method:'item/fileChange/requestApproval',params:{threadId:'qa-thread'}});
    engine.emit('notification',{method:'turn/completed',params:{threadId:'qa-thread',turn:{id:'qa-folder',status:'completed'}}});
    await assert.rejects(()=>invoke('approve',101,'accept'),/失效/);
    engine.respond=originalRespond;keepRunning=false;
    dialog.showMessageBox=originalDialog;MydexAppServer.prototype.sandboxReadiness=originalReadiness;
    MydexAppServer.prototype.startTurn=originalStart;
    await assert.rejects(()=>invoke('revealFile',path.join(outside,'private.txt')),/超出当前工作区/);
    await assert.rejects(()=>invoke('listModels'),/保存 API Key/);
    const originalMenu = Menu.buildFromTemplate;
    let contextItems;
    Menu.buildFromTemplate = items => { contextItems = items; return { popup() {} }; };
    win.webContents.emit('context-menu', {}, { isEditable:true, editFlags:{canUndo:false,canRedo:true,canCut:true,canCopy:true,canPaste:true,canSelectAll:true} });
    assert.deepEqual(contextItems.filter(i=>i.role).map(i=>i.role),['undo','redo','cut','copy','paste','selectAll']);
    assert.equal(contextItems[0].enabled,false);
    contextItems=null;win.webContents.emit('context-menu', {}, { isEditable:false,selectionText:'reply' });
    assert.equal(contextItems[0].role,'copy');
    contextItems=null;win.webContents.emit('context-menu', {}, { isEditable:false,selectionText:'' });
    assert.equal(contextItems,null);
    Menu.buildFromTemplate=originalMenu;
    await assert.rejects(()=>invoke('updateSettings',{apiBaseUrl:'http://example.com/v1'}),/HTTPS/);
    const saved=await invoke('updateSettings',{agentEngine:'web:doubao',activeWebProfile:'doubao',model:'qa-config-only'});
    assert.equal('agentEngine' in saved,false);assert.equal(saved.model,'qa-config-only');
    console.log('PASS host: actual trusted IPC, API-only migration, retired setting rejection, HTTPS validation, text/binary/large-file preview, traversal and junction containment.');
    app.exit(0);
  }catch(error){console.error(error);app.exit(1);}
});
