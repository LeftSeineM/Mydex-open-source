const assert=require('assert/strict'),fs=require('fs'),path=require('path');
const {PermissionStore,ApprovalRequests,PERMISSION_MODES:m}=require('../dist/permissions');
(async()=>{
  const dir=fs.mkdtempSync(path.join(__dirname,'..','qa-artifacts','permissions-'));
  const store=new PermissionStore(path.join(dir,'policies.json'));await store.load();
  assert.deepEqual(store.get('A',m.approval),m.approval);
  await store.set('A',m.readOnly);await store.set('B',m.full);await store.set('draft:1',m.full);
  assert.deepEqual(store.get('A',m.full),m.readOnly);
  assert.deepEqual(store.get('B',m.approval),m.full);
  const restored=new PermissionStore(path.join(dir,'policies.json'));await restored.load();
  assert.deepEqual(restored.get('A',m.full),m.readOnly);assert.deepEqual(restored.get('B',m.approval),m.full);
  assert.deepEqual(restored.get('draft:1',m.approval),m.approval);
  assert.throws(()=>store.get('',m.approval));
  const blocked=path.join(dir,'not-a-directory');fs.writeFileSync(blocked,'fixture');
  const failing=new PermissionStore(path.join(blocked,'policies.json'));
  failing.get('A',m.readOnly);await assert.rejects(()=>failing.set('A',m.full));assert.deepEqual(failing.get('A',m.approval),m.readOnly);
  await assert.rejects(()=>failing.set('new',m.full));assert.deepEqual(failing.get('new',m.approval),m.approval);
  const approvals=new ApprovalRequests();
  const add=(id,method,params={})=>approvals.add({id,method,params:{threadId:'A',turnId:'turnA',...params}});
  add(1,'item/commandExecution/requestApproval',{availableDecisions:['accept','decline']});
  assert.throws(()=>approvals.decision(1,'acceptForSession'),/不允许/);
  assert.deepEqual(approvals.decision(1,'accept'),{decision:'accept'});
  assert.throws(()=>approvals.decision(1,'accept'),/失效/);
  add('1','item/fileChange/requestApproval');assert.deepEqual(approvals.decision('1','cancel'),{decision:'cancel'});
  const requested={network:{enabled:true},fileSystem:{read:['D:\\project'],write:null}};
  add(2,'item/permissions/requestApproval',{permissions:requested});
  assert.throws(()=>approvals.decision(2,'accept'),/类型/);
  assert.throws(()=>approvals.permissions(2,true,'forever'),/无效/);
  assert.deepEqual(approvals.permissions(2,true,'turn'),{permissions:requested,scope:'turn'});
  add(3,'item/permissions/requestApproval',{permissions:requested});assert.deepEqual(approvals.permissions(3,false,'session'),{permissions:{},scope:'turn'});
  add(4,'item/permissions/requestApproval',{permissions:{network:null,fileSystem:requested.fileSystem}});
  assert.deepEqual(approvals.permissions(4,true,'session'),{permissions:{fileSystem:requested.fileSystem},scope:'session'});
  add(5,'item/commandExecution/requestApproval');add(6,'item/fileChange/requestApproval',{threadId:'B'});
  approvals.clear('A');assert.throws(()=>approvals.decision(5,'accept'),/失效/);assert.deepEqual(approvals.decision(6,'decline'),{decision:'decline'});
  add(7,'item/tool/requestUserInput',{questions:[{id:'question'}]});assert.throws(()=>approvals.answers(7,{bad:{answers:['x']}}),/无效/);
  assert.deepEqual(approvals.answers(7,{question:{answers:['yes']}}),{answers:{question:{answers:['yes']}}});
  add(8,'item/fileChange/requestApproval');approvals.resolve(8);assert.throws(()=>approvals.decision(8,'accept'),/失效/);
  console.log('PASS permissions: per-thread persistence, isolated drafts/defaults, live request binding, duplicate/stale/type rejection, engine decisions, scoped subset grants, per-thread invalidation, validated answers.');
})().catch(e=>{console.error(e);process.exitCode=1;});
