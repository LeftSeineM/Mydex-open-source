const {app,BrowserWindow,ipcMain,nativeTheme}=require('electron');
const fs=require('fs'),path=require('path'),assert=require('assert/strict');
const out=path.join(__dirname,'..','qa-artifacts');
app.setPath('userData',fs.mkdtempSync(path.join(out,'typography-')));app.disableHardwareAcceleration();
for(const stream of [process.stdout,process.stderr])stream.on('error',()=>{});
const thread={id:'typography',name:'正文排版验收',cwd:'D:\\Projects\\Mydex',turns:[]};
ipcMain.handle('qa',(_,method)=>{
  if(method==='getState')return{settings:{cwd:thread.cwd,model:'gpt-5.6-sol',apiKeyConfigured:false,theme:'light',projects:[thread.cwd]},agentState:{threads:[thread]}};
  if(method==='resumeThread')return thread;
  if(method==='getPermissions')return{sandbox:'workspace-write',approvalPolicy:'on-request'};
  if(method==='listThreads')return[thread];
  return true;
});
app.whenReady().then(async()=>{
  try{
    nativeTheme.themeSource='light';
    const win=new BrowserWindow({show:false,width:1300,height:940,webPreferences:{preload:path.join(__dirname,'qa-ui-preload.cjs'),contextIsolation:true,sandbox:true,offscreen:true,backgroundThrottling:false}});
    const run=code=>win.webContents.executeJavaScript(code),wait=()=>new Promise(r=>setTimeout(r,100));
    await win.loadFile(process.argv[2]?path.resolve(process.argv[2]):path.join(__dirname,'..','renderer','index.html'));await wait();
    await run("document.querySelector('[data-thread-id=typography]').click()");await wait();
    const render=source=>run(`(()=>{const n=document.createElement('div');window.mydexMarkdown.render(n,${JSON.stringify(source)});return n.innerHTML})()`);
    assert.equal(await render('第一行\r\n第二行\n\n\n\n下一段'),'<p>第一行 第二行</p><p>下一段</p>');
    assert.equal(await render('第一行  \n第二行\\\n第三行'),'<p>第一行<br>第二行<br>第三行</p>');
    assert.ok((await render('- 第一项\n  - 子项\n- 第二项')).includes('<ul class="tight-list"><li><p>子项</p></li></ul>'));
    assert.ok((await render('3. 三\n4. 四')).startsWith('<ol start="3"'));
    assert.ok((await render('> 引用\n>\n> 第二段')).includes('<blockquote><p>引用</p><p>第二段</p></blockquote>'));
    assert.equal(await render('**粗体**和`代码`'),'<p><strong>粗体</strong>和<code>代码</code></p>');
    assert.equal(await render('<script>alert(1)</script>'),'<p>&lt;script&gt;alert(1)&lt;/script&gt;</p>');
    const code='  const x = 1;\n\n\treturn x;\n';
    await run(`(()=>{const n=document.createElement('div');n.id='copy-fixture';document.body.append(n);window.mydexMarkdown.render(n,${JSON.stringify('```js\n'+code+'```')},{copy:value=>window.qaCopied=value});n.querySelector('button').click()})()`);await wait();
    assert.equal(await run('window.qaCopied'),code);await run("document.getElementById('copy-fixture').remove()");
    assert.ok((await render('```ts\nconst incomplete = true;')).includes('<code>const incomplete = true;</code>'));
    assert.ok((await render('````md\n```js\nx\n```\n````')).includes('```js\nx\n```\n</code>'));
    const source='# 文段与换行\n\n这是一段连续的正文，\n源文本折行后仍保持自然排版。**重点信息**和`行内代码`不会挤在一起。\n\n## 清晰的层次\n\n- 第一项较长的说明会自动换行，并且与第一行的文字对齐，不会退到项目符号下面。\n  - 嵌套说明\n- 第二项说明\n\n3. 按顺序执行\n4. 核对结果\n\n> 引用保留层次，不额外堆叠空白行。\n\n```ts\nfunction greet(name: string) {\n  return `你好，${name}`;\n}\n```\n\n第一行，保留显式换行。  \n第二行。';
    const emit=(method,params)=>win.webContents.send('qa-event','agent-notification',{method,params:{threadId:thread.id,...params}});
    for(let i=0;i<source.length;i+=7)emit('item/agentMessage/delta',{itemId:'reply',delta:source.slice(i,i+7)});
    await wait();await wait();
    const before=await run("document.querySelector('.message-content').innerHTML");
    emit('item/completed',{item:{type:'agentMessage',id:'reply',text:source}});await wait();
    assert.equal(await run("document.querySelector('.message-content').innerHTML"),before,'Streaming and final blocks must match');
    assert.equal(await run("document.querySelector('.message-content').dataset.raw"),source);
    assert.equal(await run("getComputedStyle(document.querySelector('.message-content')).whiteSpace"),'normal');
    assert.equal(await run("getComputedStyle(document.querySelector('.code-block pre')).whiteSpace"),'pre');
    await run("document.getElementById('messageList').scrollTop=0");await wait();
    fs.writeFileSync(path.join(out,'1.2.1-typography-light.png'),(await win.webContents.capturePage()).toPNG());
    nativeTheme.themeSource='dark';await wait();
    fs.writeFileSync(path.join(out,'1.2.1-typography-dark.png'),(await win.webContents.capturePage()).toPNG());
    nativeTheme.themeSource='light';win.setSize(1040,680);await wait();
    assert.ok(await run("document.getElementById('messageList').scrollWidth<=document.getElementById('messageList').clientWidth"));
    const long=Array.from({length:30},(_,i)=>'这是第 '+i+' 段正文，用于测试阅读位置。').join('\n\n');
    emit('item/agentMessage/delta',{itemId:'long',delta:long});await wait();await wait();
    await run("document.getElementById('messageList').scrollTop=0");
    emit('item/agentMessage/delta',{itemId:'long',delta:'\n\n追加内容不能抢走阅读位置。'});await wait();await wait();
    assert.equal(await run("document.getElementById('messageList').scrollTop"),0);
    emit('item/completed',{item:{type:'agentMessage',id:'long',text:long+'\n\n追加内容不能抢走阅读位置。'}});await wait();
    assert.equal(await run("document.getElementById('messageList').scrollTop"),0);
    console.log('PASS typography: semantic paragraphs, soft/hard breaks, CRLF, nested/ordered lists, quotes, safe inline/HTML, exact code copy, open/long fences, streaming/final parity, narrow layout, light/dark, reading scroll preserved.');app.exit(0);
  }catch(error){console.error(error);app.exit(1);}
});
